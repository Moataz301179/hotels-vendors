// ── Helpers ──

export function getSectorAgentById(id: string): SectorAgentDef | undefined {
  return SECTOR_AGENTS.find((a) => a.id === id);
}

export function getAgentsByLayer(layer: string): SectorAgentDef[] {
  return SECTOR_AGENTS.filter((a) => a.layer === layer);
}

export function getAgentsBySquad(squad: string): SectorAgentDef[] {
  return SECTOR_AGENTS.filter((a) => a.squad === squad);
}

export function getAllSectorAgentIds(): string[] {
  return SECTOR_AGENTS.map((a) => a.id);
}

export function getAgentDependencies(id: string): string[] {
  return getSectorAgentById(id)?.dependencies || [];
}
